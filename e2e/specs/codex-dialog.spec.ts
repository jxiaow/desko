test('locking keeps the pending approval for an explicit response after unlock', async ({ page }) => {
  await openDialog(page)
  await send(page, '锁屏审批测试')
  await expect(page.getByRole('region', { name: '待处理的 Codex 请求' })).toBeVisible()
  await e2e.emitEvent(page, 'tray-lock', { forced: true })
  await expect(page.getByRole('textbox', { name: '主密码', exact: true })).toBeVisible()
  const calls = await page.evaluate(() => (window as any).__E2E__.invocations)
  expect(calls.some((c: any) => c.cmd === 'codex_dialog_action' && c.args.action === 'respond')).toBe(false)
  await page.getByRole('textbox', { name: '主密码', exact: true }).fill('e2e-master-123')
  await page.getByRole('button', { name: '解锁', exact: true }).click()
  await page.getByRole('button', { name: '对话', exact: true }).click()
  await expect(page.getByRole('region', { name: '待处理的 Codex 请求' })).toContainText('git status --short')
})

