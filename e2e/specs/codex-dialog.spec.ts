import { test, expect, type Page } from '@playwright/test'
import { bootUnlocked, e2e } from '../helpers'

async function openDialog(page: Page, connect = true) {
  await bootUnlocked(page, { settings: { codex_enabled: 'true' } }, '/codex')
  await page.getByRole('button', { name: '对话', exact: true }).click()
  await expect(page.getByRole('heading', { name: '在项目里开始对话' })).toBeVisible()
  if (connect) {
    await e2e.queueDialog(page, 'C:\\Code\\fixture')
    await page.getByRole('button', { name: '选择工作目录', exact: true }).last().click()
    await expect(page.getByRole('status').filter({ hasText: '已连接' })).toBeVisible()
  }
}
async function send(page: Page, text: string) {
  await page.getByRole('textbox', { name: '发给 Codex 的消息' }).fill(text)
  await page.getByRole('button', { name: '发送', exact: true }).click()
}

test('stream before send response renders once, restores history and shows git changes', async ({ page }) => {
  await openDialog(page)
  await send(page, '检查当前改动')
  await expect(page.locator('.dialog-markdown')).toContainText('检查完成，没有修改文件。')
  await expect(page.locator('.dialog-user')).toHaveCount(1)
  await page.getByRole('button', { name: '选择项目', exact: true }).click()
  await page.getByRole('button', { name: '查看项目改动', exact: false }).click()
  await expect(page.locator('.git-file')).toContainText('src/示例.ts')
  await page.getByRole('button', { name: '账号', exact: true }).click()
  await page.getByRole('button', { name: '对话', exact: true }).click()
  await expect(page.locator('.dialog-markdown')).toContainText('检查完成，没有修改文件。')
  await expect(page.locator('.dialog-user')).toHaveCount(1)
  await page.screenshot({ path: '.tmp/codex-integration/dialog-light.png', fullPage: true })
  await page.evaluate(() => { document.documentElement.setAttribute('data-theme', 'ink'); document.documentElement.setAttribute('data-polarity', 'dark') })
  await page.screenshot({ path: '.tmp/codex-integration/dialog-dark.png', fullPage: true })
  await page.setViewportSize({ width: 800, height: 600 })
  if (await page.getByRole('button', { name: '关闭辅助侧栏', exact: true }).isVisible()) await page.getByRole('button', { name: '关闭辅助侧栏', exact: true }).click()
  await expect(page.getByRole('textbox', { name: '发给 Codex 的消息' })).toBeInViewport()
  await expect(page.getByRole('button', { name: '发送', exact: true })).toBeInViewport()
  await page.screenshot({ path: '.tmp/codex-integration/dialog-minimum.png', fullPage: true })
})

test('approval survives tab switch and resolves exactly once', async ({ page }) => {
  await openDialog(page)
  await send(page, '测试审批')
  await expect(page.getByRole('region', { name: '待处理的 Codex 请求' })).toContainText('git status --short')
  await page.getByRole('button', { name: '账号', exact: true }).click()
  await page.getByRole('button', { name: '对话', exact: true }).click()
  await page.getByRole('button', { name: '拒绝', exact: true }).click()
  await expect(page.getByRole('region', { name: '待处理的 Codex 请求' })).toHaveCount(0)
  const calls = await page.evaluate(() => (window as any).__E2E__.invocations)
  expect(calls.filter((c: any) => c.cmd === 'codex_dialog_action' && c.args.action === 'respond')).toHaveLength(1)
})

