test('WSL directory browsing connects directly and identifies its distribution without user input', async ({ page }) => {
  await openDialog(page, false)
  await page.getByRole('button', { name: '运行环境', exact: true }).click()
  await page.getByRole('menuitemradio', { name: 'WSL · 自动识别', exact: true }).click()
  await expect(page.getByRole('textbox', { name: 'WSL 用户', exact: true })).toHaveCount(0)
  await e2e.queueDialog(page, '\\\\wsl.localhost\\Debian\\home\\alice\\项目')
  await page.getByRole('button', { name: '浏览目录', exact: true }).click()
  await expect(page.getByRole('button', { name: '选择项目', exact: true })).toContainText('WSL · Debian')
  await expect(page.getByRole('textbox', { name: '发给 Codex 的消息' })).toBeEnabled()
  const calls = await page.evaluate(() => (window as any).__E2E__.invocations)
  const connect = calls.find((c: any) => c.cmd === 'codex_dialog_action' && c.args.action === 'connect')
  expect(connect.args.params.environment).toEqual({ kind: 'wsl', distro: '', user: '' })
})

